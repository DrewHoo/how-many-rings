// Turn each school's official brand color into two usable mark colors — one for
// the light surface, one for the dark — and emit them as CSS custom properties.
//
// Brand hexes are chosen for jerseys and letterheads, not for 14px marks on a
// warm-paper background. LSU's purple (#461D7C, OKLCH L 0.35) and Michigan's navy
// are simply too dark to read as marks in light mode; Colorado's gold is too light
// for it. So: keep the hue and as much chroma as the school's color has, and move
// only lightness until it sits inside the band the dataviz validator enforces
// (light 0.43–0.77, dark 0.48–0.67). The result still reads as the school's color
// because hue is what identity lives in.
//
// Usage: node scripts/gen-team-colors.mjs   (writes src/team-colors.css)
import fs from 'node:fs'
import path from 'node:path'

const root = path.join(import.meta.dirname, '..')
const BAND = { light: [0.43, 0.77], dark: [0.48, 0.67] }

/* ---- sRGB <-> OKLCH, matching the validator's math ---- */
const srgbToLinear = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4)
const linearToSrgb = (c) => (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055)

function hexToOklch(hex) {
  const n = parseInt(hex.slice(1), 16)
  const [r, g, b] = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((v) => srgbToLinear(v / 255))
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b)
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b)
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b)
  const L = 0.2104542553 * l + 0.7936177850 * m - 0.0040720468 * s
  const a = 1.9779984951 * l - 2.4285922050 * m + 0.4505937099 * s
  const bb = 0.0259040371 * l + 0.7827717662 * m - 0.8086757660 * s
  return [L, Math.hypot(a, bb), Math.atan2(bb, a)]
}

function oklchToHex(L, C, h) {
  const a = C * Math.cos(h), b = C * Math.sin(h)
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3
  const s = (L - 0.0894841775 * a - 1.2914855480 * b) ** 3
  const rgb = [
    +4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s,
  ].map((v) => Math.round(Math.min(1, Math.max(0, linearToSrgb(v))) * 255))
  return '#' + rgb.map((v) => v.toString(16).padStart(2, '0')).join('').toUpperCase()
}

// Sit low in the band on paper and high in the band on the dark surface: a mark
// only clears 3:1 against its background by moving away from it. Chroma is also
// floored, because a brand color that drifts under ~0.1 stops reading as a color
// at all (Colorado's gold measures 0.083 and looks gray).
const AIM = { light: [0.44, 0.58], dark: [0.60, 0.655] }  // dark ceiling clears BAND's 0.67 after rounding
const CHROMA_FLOOR = 0.105

// Clamping collapses distinctions: Oklahoma's crimson, USC's cardinal and
// Indiana's crimson all sit below the floor at slightly different lightnesses,
// and pinning each to the floor makes them the same color. Compress the whole
// set's lightness range into the aim range instead, so whatever separation the
// brand colors actually have survives the fit.
function makeFit(hexes, mode) {
  const Ls = hexes.map((x) => hexToOklch(x)[0])
  const srcLo = Math.min(...Ls), srcHi = Math.max(...Ls)
  const [lo, hi] = AIM[mode]
  const remap = srcLo === srcHi ? null : (L) => lo + ((L - srcLo) / (srcHi - srcLo)) * (hi - lo)
  return (hex, hueShift) => fit(hex, mode, remap, hueShift)
}

function fit(hex, mode, remap, hueShift = 0) {
  const [lo, hi] = AIM[mode]
  const [L, C0, h0] = hexToOklch(hex)
  const h = h0 + (hueShift * Math.PI) / 180
  const target = remap ? remap(L) : Math.min(hi, Math.max(lo, L))
  const wantC = Math.max(C0, CHROMA_FLOOR)
  // Highest chroma that survives the sRGB round-trip at this lightness and hue.
  for (let c = Math.min(wantC + 0.06, 0.33); c > 0.03; c -= 0.005) {
    const out = oklchToHex(target, c, h)
    const [L2, C2, h2] = hexToOklch(out)
    if (Math.abs(L2 - target) < 0.02 && Math.abs(h2 - h) < 0.09 && C2 >= Math.min(wantC, c) - 0.01) return out
  }
  return oklchToHex(target, Math.min(C0, 0.09), h)
}

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '')
const schools = JSON.parse(fs.readFileSync(path.join(root, 'data', 'school-colors.json'), 'utf8')).schools

const bases = Object.values(schools).map((v) => v.mark ?? v.primary)
const fitLight = makeFit(bases, 'light')
const fitDark = makeFit(bases, 'dark')

const rows = Object.entries(schools).map(([school, v]) => {
  const base = v.mark ?? v.primary
  return {
    school, key: slug(school), base, note: v.note,
    // A school that publishes its own accessible variant beats anything computed.
    light: v.lightOverride ?? fitLight(base, v.hueShift),
    dark: v.darkOverride ?? fitDark(base, v.hueShift),
  }
})

const css = `/* GENERATED by scripts/gen-team-colors.mjs — do not edit by hand.
   Each school's official color, nudged in lightness only (hue and chroma kept) so
   it reads as a mark on both surfaces. Source hexes and citations live in
   data/school-colors.json. */
:root {
${rows.map((r) => `  --team-${r.key}: ${r.light};`).join('\n')}
}

@media (prefers-color-scheme: dark) {
  :root:where(:not([data-theme="light"])) {
${rows.map((r) => `    --team-${r.key}: ${r.dark};`).join('\n')}
  }
}
`
fs.writeFileSync(path.join(root, 'src', 'team-colors.css'), css)

console.log(`${rows.length} schools → src/team-colors.css`)
for (const r of rows) {
  const moved = r.base.toUpperCase() !== r.light || r.base.toUpperCase() !== r.dark
  console.log(`  ${r.school.padEnd(14)} ${r.base}  light ${r.light}  dark ${r.dark}${moved ? '' : '  (unchanged)'}`)
}
